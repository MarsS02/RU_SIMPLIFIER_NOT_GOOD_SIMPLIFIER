@pytest.fixture(scope="module")
def analyzed():
    return analyze_text("\n".join(SENTENCES_50))


def test_all_fifty_sentences_parsed(analyzed):
    assert len(analyzed["sentences"]) == 50


def test_contract_fields_present(analyzed):
    assert analyzed["text"]
    for i, sent in enumerate(analyzed["sentences"]):
        assert sent["id"] == i
        assert isinstance(sent["text"], str) and sent["text"]
        assert isinstance(sent["root"], int)
        assert 0 <= sent["root"] < len(sent["tokens"])
        for j, tok in enumerate(sent["tokens"]):
            assert tok["id"] == j
            assert set(tok) >= {"id", "text", "lemma", "pos", "morph",
                                "head", "dep", "ner", "is_stop"}
            assert isinstance(tok["morph"], dict)
            assert isinstance(tok["is_stop"], bool)
            assert tok["head"] != j or sent["root"] == j  # root указывает на себя
            assert -1 <= tok["head"] < len(sent["tokens"])
        for span in sent["ner_spans"]:
            assert set(span) >= {"text", "start", "end", "label"}
            assert span["text"] in sent["text"]


def test_result_is_json_serializable(analyzed):
    s = json.dumps(analyzed, ensure_ascii=False)
    assert json.loads(s) == analyzed


def test_determinism_on_corpus(analyzed):
    again = analyze_text("\n".join(SENTENCES_50))
    assert again == analyzed


def test_content_preserved_no_clauses_dropped(analyzed):
    """INV-1 (прогретур для анализатора): содержательные слова не теряются."""
    src_words = set()
    for s in SENTENCES_50:
        src_words.update(w.strip(".,:;!?—").lower() for w in s.split())
    out_words = {t["text"].lower() for sent in analyzed["sentences"] for t in sent["tokens"]}
    missing = {w for w in src_words if w and w not in out_words}
    assert not missing, f"потеряны слова: {missing}"
